# shellcheck shell=bash
# Build step: generate build/AGENTS.full.md, check out the approved
# third-party skills, apply skill description overrides and resolve core/mcp.json.

AGENTS_MAX_BYTES=32768   # Codex project-doc limit

# Print a markdown file without its leading YAML frontmatter and leading blank lines.
strip_frontmatter() {
  awk '
    NR == 1 && /^---[[:space:]]*$/ { fm = 1; next }
    fm { if (/^---[[:space:]]*$/) fm = 0; next }
    !started && /^[[:space:]]*$/ { next }
    { started = 1; print }
  ' "$1"
}

_install_file() { mkdir -p "$(dirname "$2")" && cp "$1" "$2"; }

build_agents_md() {
  local out="$ROOT/build/AGENTS.full.md" tmp f size
  if [ ! -f "$ROOT/core/AGENTS.md" ]; then
    warn "core/AGENTS.md missing; build/AGENTS.full.md not generated"
    return 0
  fi
  tmp="$TMP_DIR/AGENTS.full.md"
  {
    printf '%s\n\n' '<!-- Generated by agent-setup from core/; edit core/ and re-run install.sh -->'
    cat "$ROOT/core/AGENTS.md"
    for f in "$ROOT"/core/rules/*.md; do
      [ -f "$f" ] || continue
      printf '\n'
      strip_frontmatter "$f"
    done
  } >"$tmp"
  size=$(wc -c <"$tmp" | tr -d ' ')
  if [ "$size" -gt "$AGENTS_MAX_BYTES" ]; then
    warn "build/AGENTS.full.md is $size bytes, over the 32 KiB Codex limit; Codex will truncate it"
  fi
  if [ -f "$out" ] && cmp -s "$tmp" "$out"; then
    log "build/AGENTS.full.md up to date ($size bytes)"
    return 0
  fi
  act "generate build/AGENTS.full.md ($size bytes)" _install_file "$tmp" "$out"
}

# Sparse checkout state of a vendor checkout: its patterns, or "" for the whole tree.
_sparse_state() {
  [ "$(git -C "$1" config --bool core.sparseCheckout 2>/dev/null)" = true ] || return 0
  cat "$1/.git/info/sparse-checkout" 2>/dev/null || true
}

# Re-apply the sparse patterns to the work tree. "sparse-checkout reapply"
# (git 2.27+) also drops files checked out before sparse checkout was on;
# older git falls back to read-tree.
_sparse_update() {
  git -C "$1" update-index -q --refresh >/dev/null 2>&1 || true
  git -C "$1" sparse-checkout reapply >/dev/null 2>&1 || git -C "$1" read-tree -mu HEAD
}

# _apply_sparse DIR PATTERNS: limit the work tree to PATTERNS ("" = whole tree).
_apply_sparse() {
  local dir=$1 want=$2
  mkdir -p "$dir/.git/info" || return 1
  if [ -n "$want" ]; then
    git -C "$dir" config core.sparseCheckout true &&
      printf '%s\n' "$want" >"$dir/.git/info/sparse-checkout" &&
      _sparse_update "$dir"
  else
    # Widen to everything first, then switch sparse checkout off.
    git -C "$dir" config core.sparseCheckout true &&
      printf '/*\n' >"$dir/.git/info/sparse-checkout" &&
      _sparse_update "$dir" &&
      git -C "$dir" config core.sparseCheckout false &&
      rm -f "$dir/.git/info/sparse-checkout"
  fi
}

# _sparse_patterns ENTRIES REPO: sparse patterns for every lock path of REPO,
# one per line; prints nothing when any path is "." (whole tree).
_sparse_patterns() {
  printf '%s' "$1" | awk -F '\t' -v repo="$2" '
    $2 == repo { if ($3 == ".") full = 1; else if (!seen[$3]++) out = out "/" $3 "/\n" }
    END { if (!full) printf "%s", out }'
}

# _fetch_new DIR URL COMMIT PATTERNS: shallow, blob-less fetch of COMMIT into
# a new DIR, checking out only PATTERNS ("" = whole tree). Built next to DIR
# and moved into place, so a failed fetch leaves nothing behind.
_fetch_new() {
  local dir=$1 url=$2 ref=$3 want=$4 tmp="$1.tmp"
  rm -rf "$tmp" && mkdir -p "$tmp" &&
    git -C "$tmp" init -q &&
    git -C "$tmp" remote add origin "$url" &&
    git -C "$tmp" config remote.origin.promisor true &&
    git -C "$tmp" config remote.origin.partialclonefilter blob:none &&
    { [ -z "$want" ] || {
      mkdir -p "$tmp/.git/info" &&
        git -C "$tmp" config core.sparseCheckout true &&
        printf '%s\n' "$want" >"$tmp/.git/info/sparse-checkout"
    }; } &&
    _git_net -C "$tmp" fetch -q --depth 1 --filter=blob:none origin "$ref" &&
    git -C "$tmp" -c advice.detachedHead=false checkout -q --detach 'FETCH_HEAD^{commit}' &&
    mv "$tmp" "$dir" ||
    { rm -rf "$tmp"; return 1; }
}

# _vendor_checkout DIR COMMIT: move the checkout in DIR to COMMIT in place.
_vendor_checkout() {
  git -C "$1" cat-file -e "$2^{commit}" 2>/dev/null ||
    _git_net -C "$1" fetch -q --depth 1 --filter=blob:none origin "$2" || return 1
  git -C "$1" -c advice.detachedHead=false checkout -q --detach "$2"
}

# _vendor_repo REPO COMMIT PATTERNS: bring vendor/<owner>__<repo>/ to COMMIT
# (the approved one), limited to PATTERNS. The checkout moves in place, so
# links into it never dangle; when the fetch fails the last good copy is kept.
# Returns 1 when there is no checkout at all.
_vendor_repo() {
  local repo=$1 sha=$2 want=$3 base dir old
  base="${repo%%/*}__${repo#*/}"
  dir="$ROOT/vendor/$base"
  if [ ! -d "$dir/.git" ]; then
    act "fetch $repo at ${sha:0:12} into vendor/$base" _fetch_new "$dir" "$(gh_url "$repo")" "$sha" "$want"
    [ "$DRY_RUN" = 1 ] || [ -d "$dir/.git" ]
    return
  fi
  if [ "$(_sparse_state "$dir")" != "$want" ]; then
    act "update checked-out paths of vendor/$base" _apply_sparse "$dir" "$want"
  fi
  old=$(git -C "$dir" rev-parse HEAD 2>/dev/null || true)
  [ "$old" != "$sha" ] || return 0
  act "update vendor/$base: ${old:0:12} -> ${sha:0:12} (approved)" _vendor_checkout "$dir" "$sha"
  return 0
}

# vendor/ dirs in use this run, one per line (for cleanup_vendor).
VENDOR_DIRS=$'\n'

# Check out every core/skills.lock repo at its approved commit into
# vendor/<owner>__<repo>/ (only the paths the lock lists for it; the whole
# tree for a repo Antigravity installs as a plugin from there) and record
# each skill in VENDORED_SKILLS as "name<TAB>skill dir<TAB>skip<TAB>plugin"
# (skip: agents, or "-"; plugin: the core/plugins.lock plugin it is a copy
# of, or ""). A repo without an approved commit is skipped.
vendor_skills() {
  local name repo path opts entries="" repo_list dir src ok=$'\n' plugin skip sha want
  while IFS=$'\t' read -r name repo path opts; do
    [ -n "$name" ] || continue
    case $repo in */*) ;; *) warn "skills.lock: bad entry for '$name'; skipped"; continue ;; esac
    path=${path:-.}
    path=${path%/}
    entries="$entries$name"$'\t'"$repo"$'\t'"$path"$'\t'"$opts"$'\n'
  done < <(lock_lines "$ROOT/core/skills.lock")
  repo_list=$(printf '%s' "$entries" | cut -f2 | awk '!seen[$0]++')
  while IFS= read -r repo <&3; do
    [ -n "$repo" ] || continue
    VENDOR_DIRS="$VENDOR_DIRS${repo%%/*}__${repo#*/}"$'\n'
    sha=$(approved "$(repo_item "$repo")")
    [ -n "$sha" ] || continue
    want=$(_sparse_patterns "$entries" "$repo")
    plugin=$(plugin_for_repo "$repo")
    if [ -n "$plugin" ] && [ -n "$(plugin_ids antigravity | awk -F '\t' -v n="$plugin" '$1 == n')" ]; then want=""; fi
    if _vendor_repo "$repo" "$sha" "$want"; then ok="$ok$repo"$'\n'; fi
  done 3<<EOF
$repo_list
EOF
  while IFS=$'\t' read -r name repo path opts; do
    [ -n "$name" ] || continue
    in_list "$ok" "$repo" || continue
    dir="$ROOT/vendor/${repo%%/*}__${repo#*/}"
    if [ "$path" = "." ]; then src=$dir; else src="$dir/$path"; fi
    if [ "$DRY_RUN" != 1 ] && [ ! -d "$src" ]; then
      warn "skills.lock: '$path' not found in $repo at the approved commit; skill $name skipped"
      continue
    fi
    plugin=$(plugin_for_repo "$repo")
    skip=$(opt_value "$opts" skip)
    # "-" for none: read collapses empty tab-separated fields.
    VENDORED_SKILLS="$VENDORED_SKILLS$name"$'\t'"$src"$'\t'"${skip:--}"$'\t'"$plugin"$'\n'
  done <<EOF
$entries
EOF
}

# _links_into DIR: the first skill link (in the skill dirs agents read) that
# points into DIR, or "".
_links_into() {
  local d e t
  while IFS= read -r d; do
    for e in "$d"/*; do
      [ -L "$e" ] || continue
      t=$(readlink "$e")
      case $t in "$1" | "$1"/*) printf '%s' "$e"; return 0 ;; esac
    done
  done < <(printf '%s\n' "$SKILL_DIRS_DONE" "$HOME/.agents/skills" "$HOME/.claude/skills" "$HOME/.gemini/config/skills" "$HOME/.kiro/skills" | awk 'NF && !seen[$0]++')
}

# Remove vendor/ dirs that no skills.lock repo uses any more (such as the old
# pinned <owner>__<repo>@<sha> dirs). A dir that a skill link still points
# into (an agent not configured this run) is kept and reported.
cleanup_vendor() {
  local d base used
  for d in "$ROOT"/vendor/*; do
    [ -d "$d" ] || continue
    base=$(basename "$d")
    in_list "$VENDOR_DIRS" "$base" && continue
    used=$(_links_into "$d")
    if [ -n "$used" ]; then
      log "NOTE: kept vendor/$base: $(pretty "$used") still links into it; it is removed once no link points there"
      continue
    fi
    act "remove unused vendor/$base" rm -rf "$d"
  done
}

# Print SKILL.md with the frontmatter description replaced by $SKILL_DESC
# (single-line, quoted, folded or literal block forms). Fails if none found.
# Keeps a missing final newline missing, so only the description differs.
_set_description() {
  local eol=1
  [ -z "$(tail -c 1 "$1")" ] || eol=0
  SKILL_DESC=$2 awk '
    function q(s) { gsub(/\\/, "\\\\", s); gsub(/"/, "\\\"", s); return "\"" s "\"" }
    NR == 1 && /^---[[:space:]]*$/ { fm = 1; print; next }
    fm && /^---[[:space:]]*$/ { fm = 0; skip = 0; print; next }
    fm && skip && /^[[:space:]]/ { next }
    fm { skip = 0 }
    fm && /^description:/ { print "description: " q(ENVIRON["SKILL_DESC"]); skip = 1; done = 1; next }
    { print }
    END { if (!done) exit 3 }
  ' "$1" | if [ "$eol" = 1 ]; then cat; else perl -pe 'chomp if eof'; fi
}

_replace_dir() { rm -rf "$2" && mkdir -p "$(dirname "$2")" && mv "$1" "$2"; }

# Mark a skill copy explicit-only for Codex: agents/openai.yaml gets
# policy.allow_implicit_invocation: false unless it already has a policy.
_explicit_only() {
  local y="$1/agents/openai.yaml"
  mkdir -p "$1/agents" || return 1
  [ -f "$y" ] && grep -q '^policy:' "$y" && return 0
  if [ -s "$y" ] && [ -n "$(tail -c 1 "$y")" ]; then printf '\n' >>"$y"; fi
  printf 'policy:\n  allow_implicit_invocation: false\n' >>"$y"
}

# For each core/skills.overrides entry ("name<TAB>description[<TAB>explicit]"),
# build build/skills/<name>/ as a copy of the vendored skill with that
# description (and, with "explicit", marked explicit-only for Codex), and point
# VENDORED_SKILLS at the copy. The vendor checkout is never edited.
override_skills() {
  local file="$ROOT/core/skills.overrides" name desc flags src meta out stage rest
  while IFS=$'\t' read -r name desc flags; do
    [ -n "$name" ] && [ -n "$desc" ] || continue
    src=$(printf '%s' "$VENDORED_SKILLS" | awk -F '\t' -v n="$name" '$1 == n { print $2; exit }')
    meta=$(printf '%s' "$VENDORED_SKILLS" | awk -F '\t' -v n="$name" '$1 == n { print $3 "\t" $4; exit }')
    if [ -z "$src" ]; then
      warn "skills.overrides: '$name' is not a vendored skill; skipped"
      continue
    fi
    out="$ROOT/build/skills/$name"
    if [ -f "$src/SKILL.md" ]; then
      stage="$TMP_DIR/skill-$name"
      rm -rf "$stage" && cp -Rp "$src" "$stage" && rm -rf "$stage/.git" || { warn "could not copy skill $name"; continue; }
      if ! _set_description "$src/SKILL.md" "$desc" >"$stage/SKILL.md"; then
        warn "skills.overrides: no description in $name/SKILL.md; override skipped"
        continue
      fi
      if [ "$flags" = explicit ] && ! _explicit_only "$stage"; then
        warn "skills.overrides: could not mark $name explicit-only"
      fi
      if [ -d "$out" ] && diff -rq "$stage" "$out" >/dev/null 2>&1; then
        log "build/skills/$name up to date"
      else
        act "build build/skills/$name (description override)" _replace_dir "$stage" "$out"
      fi
    elif [ "$DRY_RUN" = 1 ]; then
      act "build build/skills/$name (description override)"
    else
      warn "skills.overrides: $name has no SKILL.md; override skipped"
      continue
    fi
    rest=$(printf '%s' "$VENDORED_SKILLS" | awk -F '\t' -v n="$name" '$1 != n')
    [ -z "$rest" ] || rest="$rest"$'\n'
    VENDORED_SKILLS="$rest$name"$'\t'"$out"$'\t'"$meta"$'\n'
  done < <(lock_lines "$file")
}

# MCP_JSON: core/mcp.json with each pinned server's {version} set to the
# version approved on this machine; the previously approved args join its
# oldArgs, so a config at that version is moved to the new one. A pinned
# server without an approved version is left out.
MCP_JSON="$ROOT/core/mcp.json"
resolve_mcp() {
  MCP_JSON="$TMP_DIR/mcp.json"
  jq --argjson ap "$APPROVED" '
    del(._comment)
    | .servers |= with_entries(
        if .value.pin then
          .key as $n | ($ap[$n].version // "") as $v | ($ap[$n].previous // "") as $p
          | if $v == "" then empty else
              .value |= ((.args // []) as $a
                | .args = ($a | map(gsub("\\{version\\}"; $v)))
                | .oldArgs = ((.oldArgs // []) + (if $p != "" then [$a | map(gsub("\\{version\\}"; $p))] else [] end))
                | del(.pin))
            end
        else . end)' "$ROOT/core/mcp.json" >"$MCP_JSON"
}
